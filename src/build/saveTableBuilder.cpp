#include "saveTableBuilder.h"

#include <algorithm>
#include <sstream>
#include <string>
#include <vector>

#include "../project/assetManager.h"
#include "../project/assets/saveFileAsset.h"
#include "../utils/fs.h"
#include "../utils/logger.h"

namespace
{
  using Project::Assets::SaveFileAsset;

  // Match P64::Save::MAX_SLOTS_4K / MAX_SLOTS_16K. Keep the cap as a
  // generous-margin worst-case (16K cart) — the build only fails when the
  // project would not even fit on a 16K cart.
  constexpr uint32_t SLOT_CAP_16K = 500;

  const char* typeName(SaveFileAsset::FieldType t)
  {
    switch (t) {
      case SaveFileAsset::FT_INT:    return "int32_t";
      case SaveFileAsset::FT_FLOAT:  return "float";
      case SaveFileAsset::FT_BOOL:   return "bool";
      case SaveFileAsset::FT_STRING: return "const char*";
      case SaveFileAsset::FT_VEC2:   return "Game::Save::Vec2";
      case SaveFileAsset::FT_VEC3:   return "Game::Save::Vec3";
    }
    return "int32_t";
  }

  // Capitalize first char so setX/getX read naturally on lowerCamel field names.
  std::string upper1(const std::string &s)
  {
    if (s.empty()) return s;
    std::string r = s;
    if (r[0] >= 'a' && r[0] <= 'z') r[0] = (char)(r[0] - 'a' + 'A');
    return r;
  }

  // Same identifier rule the inspector enforces. Belt-and-braces for assets
  // that may have been created before the inspector existed (or hand-edited).
  std::string sanitizeIdent(const std::string &raw)
  {
    std::string g;
    g.reserve(raw.size());
    for (char c : raw) {
      if ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z')
          || (c >= '0' && c <= '9') || c == '_') {
        g.push_back(c);
      } else {
        g.push_back('_');
      }
    }
    if (!g.empty() && g[0] >= '0' && g[0] <= '9') g.insert(g.begin(), '_');
    return g;
  }

  std::string fallbackGroupName(const std::string &assetName, uint64_t uuid)
  {
    std::string base = assetName;
    auto dot = base.rfind('.');
    if (dot != std::string::npos) base.erase(dot);
    base = sanitizeIdent(base);
    if (base.empty()) base = "G_" + std::to_string(uuid);
    return base;
  }
}

bool Build::buildSaveTable(Project::Project &project)
{
  const auto &saves = project.getAssets().getTypeEntries(Project::FileType::SAVE_FILE);

  // Stable, deterministic order (group uuid). Slot indices are positionally
  // derived, so this ordering must be reproducible across rebuilds.
  std::vector<const Project::AssetManagerEntry*> ordered;
  ordered.reserve(saves.size());
  for (const auto &e : saves) {
    if (e.saveFileAsset) ordered.push_back(&e);
  }
  std::sort(ordered.begin(), ordered.end(),
    [](const Project::AssetManagerEntry *a, const Project::AssetManagerEntry *b) {
      return a->saveFileAsset->uuid < b->saveFileAsset->uuid;
    });

  // First pass: assign slot indices and detect duplicate group names.
  uint32_t totalSlots = 0;
  struct GroupOut {
    std::string ns;
    const SaveFileAsset *asset{};
    std::vector<uint32_t> fieldSlots;  // base slot for each field
  };
  std::vector<GroupOut> groups;
  groups.reserve(ordered.size());

  for (const auto *e : ordered) {
    GroupOut g{};
    g.asset = e->saveFileAsset.get();
    g.ns = sanitizeIdent(g.asset->groupName);
    if (g.ns.empty()) g.ns = fallbackGroupName(e->name, g.asset->uuid);
    for (const auto &f : g.asset->fields) {
      g.fieldSlots.push_back(totalSlots);
      totalSlots += SaveFileAsset::fieldSlotCount(f);
    }
    groups.push_back(std::move(g));
  }

  // Disambiguate duplicate group names by suffixing the asset uuid (rare —
  // the inspector enforces sanitized names but not uniqueness).
  for (size_t i = 0; i < groups.size(); ++i) {
    for (size_t j = i + 1; j < groups.size(); ++j) {
      if (groups[j].ns == groups[i].ns) {
        groups[j].ns += "_" + std::to_string(groups[j].asset->uuid);
      }
    }
  }

  if (totalSlots > SLOT_CAP_16K) {
    Utils::Logger::log(
      "Save schema requires " + std::to_string(totalSlots)
      + " slots, exceeds 16K EEPROM cap of " + std::to_string(SLOT_CAP_16K),
      Utils::Logger::LEVEL_ERROR);
    return false;
  }

  // ---------------- header ----------------
  std::ostringstream h;
  h << "// NOTE: This file is autogenerated. Do not edit manually.\n";
  h << "#pragma once\n";
  h << "#include <cstdint>\n";
  h << "\n";
  h << "namespace Game::Save\n";
  h << "{\n";
  h << "  // Total int32 slot count this project consumes in P64::Save's buffer.\n";
  h << "  inline constexpr uint32_t TOTAL_SLOTS = " << totalSlots << ";\n";
  h << "\n";
  h << "  // Convenience aggregates for FT_VEC2 / FT_VEC3 fields. Defined here\n";
  h << "  // (rather than pulling glm into engine code) so the runtime header\n";
  h << "  // dependency is just <cstdint>.\n";
  h << "  struct Vec2 { float x, y; };\n";
  h << "  struct Vec3 { float x, y, z; };\n";
  h << "\n";
  h << "  // Calls P64::Save::init(TOTAL_SLOTS), then seeds any field whose\n";
  h << "  // current EEPROM value equals zero with its declared default. Returns\n";
  h << "  // false only when EEPROM is absent or P64::Save::init refuses the\n";
  h << "  // requested slot count.\n";
  h << "  bool init();\n";

  for (const auto &g : groups) {
    h << "\n";
    h << "  namespace " << g.ns << "\n";
    h << "  {\n";
    for (size_t fi = 0; fi < g.asset->fields.size(); ++fi) {
      const auto &f = g.asset->fields[fi];
      if (f.name.empty()) continue;
      std::string id = sanitizeIdent(f.name);
      if (id.empty()) continue;
      const char *t = typeName(f.type);
      h << "    " << t << " get" << upper1(id) << "();\n";
      if (f.type == SaveFileAsset::FT_STRING) {
        h << "    void set" << upper1(id) << "(const char* value);\n";
      } else {
        h << "    void set" << upper1(id) << "(" << t << " value);\n";
      }
      (void)fi;
    }
    h << "  }\n";
  }
  h << "}\n";

  // ---------------- cpp ----------------
  std::ostringstream c;
  c << "// NOTE: This file is autogenerated. Do not edit manually.\n";
  c << "#include \"saveTable.h\"\n";
  c << "#include \"save/save.h\"\n";
  c << "#include \"save/saveAutoInit.h\"\n";
  c << "#include <cstring>\n";
  c << "\n";
  c << "namespace Game::Save\n";
  c << "{\n";

  // Per-field slot constants and accessor implementations.
  for (const auto &g : groups) {
    c << "  namespace " << g.ns << "\n";
    c << "  {\n";
    for (size_t fi = 0; fi < g.asset->fields.size(); ++fi) {
      const auto &f = g.asset->fields[fi];
      if (f.name.empty()) continue;
      std::string id = sanitizeIdent(f.name);
      if (id.empty()) continue;
      uint32_t slot = g.fieldSlots[fi];

      switch (f.type) {
        case SaveFileAsset::FT_INT:
          c << "    int32_t get" << upper1(id) << "() { return P64::Save::getInt(" << slot << "); }\n";
          c << "    void    set" << upper1(id) << "(int32_t v) { P64::Save::setInt(" << slot << ", v); }\n";
          break;
        case SaveFileAsset::FT_FLOAT:
          c << "    float get" << upper1(id) << "() { return P64::Save::getFloat(" << slot << "); }\n";
          c << "    void  set" << upper1(id) << "(float v) { P64::Save::setFloat(" << slot << ", v); }\n";
          break;
        case SaveFileAsset::FT_BOOL:
          c << "    bool get" << upper1(id) << "() { return P64::Save::getBool(" << slot << "); }\n";
          c << "    void set" << upper1(id) << "(bool v) { P64::Save::setBool(" << slot << ", v); }\n";
          break;
        case SaveFileAsset::FT_STRING: {
          uint32_t slots   = SaveFileAsset::fieldSlotCount(f);
          uint32_t maxLen  = f.stringLen;
          c << "    static char s_buf_" << id << "[" << (maxLen + 1) << "];\n";
          c << "    const char* get" << upper1(id) << "() {\n";
          c << "      char *out = s_buf_" << id << ";\n";
          c << "      for (uint32_t i = 0; i < " << slots << "; ++i) {\n";
          c << "        int32_t w = P64::Save::getInt(" << slot << " + i);\n";
          c << "        for (int b = 0; b < 4; ++b) {\n";
          c << "          uint32_t off = i*4 + b;\n";
          c << "          if (off >= " << maxLen << ") break;\n";
          c << "          out[off] = (char)((w >> (b*8)) & 0xFF);\n";
          c << "        }\n";
          c << "      }\n";
          c << "      out[" << maxLen << "] = '\\0';\n";
          c << "      return out;\n";
          c << "    }\n";
          c << "    void set" << upper1(id) << "(const char* value) {\n";
          c << "      const char *src = value ? value : \"\";\n";
          c << "      for (uint32_t i = 0; i < " << slots << "; ++i) {\n";
          c << "        int32_t w = 0;\n";
          c << "        for (int b = 0; b < 4; ++b) {\n";
          c << "          uint32_t off = i*4 + b;\n";
          c << "          char ch = (off < " << maxLen << ") ? src[off] : '\\0';\n";
          c << "          if (off > 0 && off >= " << maxLen << ") ch = '\\0';\n";
          c << "          w |= ((int32_t)(uint8_t)ch) << (b*8);\n";
          c << "          if (ch == '\\0' && off >= " << maxLen << ") break;\n";
          c << "        }\n";
          c << "        P64::Save::setInt(" << slot << " + i, w);\n";
          c << "      }\n";
          c << "    }\n";
          break;
        }
        case SaveFileAsset::FT_VEC2:
          c << "    Vec2 get" << upper1(id) << "() { return Vec2{ P64::Save::getFloat(" << slot << "), P64::Save::getFloat(" << (slot+1) << ") }; }\n";
          c << "    void set" << upper1(id) << "(Vec2 v) { P64::Save::setFloat(" << slot << ", v.x); P64::Save::setFloat(" << (slot+1) << ", v.y); }\n";
          break;
        case SaveFileAsset::FT_VEC3:
          c << "    Vec3 get" << upper1(id) << "() { return Vec3{ P64::Save::getFloat(" << slot << "), P64::Save::getFloat(" << (slot+1) << "), P64::Save::getFloat(" << (slot+2) << ") }; }\n";
          c << "    void set" << upper1(id) << "(Vec3 v) { P64::Save::setFloat(" << slot << ", v.x); P64::Save::setFloat(" << (slot+1) << ", v.y); P64::Save::setFloat(" << (slot+2) << ", v.z); }\n";
          break;
      }
    }
    c << "  }\n\n";
  }

  // init() and the strong override of P64::saveAutoInit().
  c << "  bool init()\n";
  c << "  {\n";
  if (totalSlots == 0) {
    c << "    return P64::Save::init(1);\n";
  } else {
    c << "    if (!P64::Save::init(TOTAL_SLOTS)) return false;\n";
    c << "    // Seed defaults: only when the slot is still zero (fresh EEPROM).\n";
    c << "    // We never overwrite existing player data.\n";

    for (const auto &g : groups) {
      for (size_t fi = 0; fi < g.asset->fields.size(); ++fi) {
        const auto &f = g.asset->fields[fi];
        if (f.name.empty()) continue;
        std::string id = sanitizeIdent(f.name);
        if (id.empty()) continue;
        uint32_t slot = g.fieldSlots[fi];

        switch (f.type) {
          case SaveFileAsset::FT_INT:
            if (f.defInt != 0) {
              c << "    if (P64::Save::getInt(" << slot << ") == 0) P64::Save::setInt(" << slot << ", " << f.defInt << ");\n";
            }
            break;
          case SaveFileAsset::FT_FLOAT:
            if (f.defFloat != 0.0f) {
              c << "    if (P64::Save::getInt(" << slot << ") == 0) P64::Save::setFloat(" << slot << ", " << f.defFloat << "f);\n";
            }
            break;
          case SaveFileAsset::FT_BOOL:
            if (f.defBool) {
              c << "    if (P64::Save::getInt(" << slot << ") == 0) P64::Save::setBool(" << slot << ", true);\n";
            }
            break;
          case SaveFileAsset::FT_STRING: {
            if (!f.defString.empty()) {
              c << "    if (P64::Save::getInt(" << slot << ") == 0) " << g.ns << "::set" << upper1(id) << "(\"";
              for (char ch : f.defString) {
                if (ch == '\\' || ch == '"') c << '\\';
                if (ch == '\n') { c << "\\n"; continue; }
                c << ch;
              }
              c << "\");\n";
            }
            break;
          }
          case SaveFileAsset::FT_VEC2:
            if (f.defVec[0] != 0.0f || f.defVec[1] != 0.0f) {
              c << "    if (P64::Save::getInt(" << slot << ") == 0 && P64::Save::getInt(" << (slot+1) << ") == 0) "
                << g.ns << "::set" << upper1(id) << "(Vec2{" << f.defVec[0] << "f, " << f.defVec[1] << "f});\n";
            }
            break;
          case SaveFileAsset::FT_VEC3:
            if (f.defVec[0] != 0.0f || f.defVec[1] != 0.0f || f.defVec[2] != 0.0f) {
              c << "    if (P64::Save::getInt(" << slot << ") == 0 && P64::Save::getInt(" << (slot+1) << ") == 0 && P64::Save::getInt(" << (slot+2) << ") == 0) "
                << g.ns << "::set" << upper1(id) << "(Vec3{" << f.defVec[0] << "f, " << f.defVec[1] << "f, " << f.defVec[2] << "f});\n";
            }
            break;
        }
      }
    }
    c << "    P64::Save::commit();\n";
    c << "    return true;\n";
  }
  c << "  }\n";
  c << "}\n";
  c << "\n";
  c << "// Strong override of the engine's weak P64::saveAutoInit(). main.cpp\n";
  c << "// calls this before the GAME_INIT global-script hook.\n";
  c << "namespace P64 { void saveAutoInit() { Game::Save::init(); } }\n";

  // ---------------- write ----------------
  fs::path outDir = fs::path(project.getPath()) / "src" / "p64";
  fs::create_directories(outDir);
  Utils::FS::saveTextFile((outDir / "saveTable.h").string(), h.str());
  Utils::FS::saveTextFile((outDir / "saveTable.cpp").string(), c.str());
  return true;
}
